// ─── Helper functions ──────────────────────────────────────────────────────────

// Platforms with active affiliate relationships, shown on public pages
const ACTIVE_PLATFORMS = new Set(["Sephora PH", "Shopee PH"])

export function isPublicDeal(deal: Deal): boolean {
  return ACTIVE_PLATFORMS.has(deal.platform) && Boolean(deal.imageUrl)
}

export function getDealBySlug(slug: string): Deal | undefined {
  return deals.find((deal) => deal.slug === slug && isPublicDeal(deal))
}

// Discounts at or above this are treated as suspicious. A listed 80%+ "discount"
// often reflects an inflated original price, so we demote these from the homepage
// featured row and Top Picks, and soften how the discount is shown on the card.
export const SUSPICIOUS_DISCOUNT = 80
export function isSuspiciousDiscount(deal: Deal): boolean {
  return deal.discount >= SUSPICIOUS_DISCOUNT
}

// Shared warning shown wherever a suspicious (80%+) discount is displayed.
export const SUSPICIOUS_DISCOUNT_NOTE =
  "Very high listed discounts can reflect inflated original prices. Compare the final price, reviews, and seller details before buying."

// Higher-uncertainty deals we keep out of the first impression: battery, charging,
// dashcam, OBD2, smartwatch, and solar-lighting electronics, where quality and
// safety vary more and buyers should check reviews and seller details first.
const RISKY_ELECTRONICS = /\b(power ?bank|wireless charger|charger|dash ?cam|obd-?2|obd-?ii|smart ?watch|earbuds?|earphones?|microphone|mini camera|car polisher)\b|\bsolar (lights?|lamp|wall|garden|corner|string|panel)\b/i
export function isRiskyElectronics(deal: Deal): boolean {
  return RISKY_ELECTRONICS.test(deal.title)
}

// Risk rank for default ordering (lower sorts first). Extreme discounts are demoted
// hardest, then other suspicious discounts, then higher-uncertainty electronics, then
// general electronics, so safe practical (non-electronics) picks lead the list.
function dealRiskRank(deal: Deal): number {
  if (deal.discount >= 90) return 4
  if (isSuspiciousDiscount(deal)) return 3
  if (isRiskyElectronics(deal)) return 2
  if (deal.category === "Electronics") return 1
  return 0
}

// Default ordering for public deal lists. Keeps safe, practical, higher-confidence
// picks first and demotes suspicious discounts and higher-uncertainty electronics,
// so the first impression is not led by the biggest or least predictable items.
export function compareDealsForDefault(a: Deal, b: Deal): number {
  const ra = dealRiskRank(a), rb = dealRiskRank(b)
  if (ra !== rb) return ra - rb                                           // safer items first
  if (b.sulitScore !== a.sulitScore) return b.sulitScore - a.sulitScore   // higher SulitScore first
  return b.discount - a.discount                                          // then a larger (reasonable) discount
}

// All active deals (active platform and has image), in the recommended default order.
export function getActiveDeals(now: Date = new Date()): Deal[] {
  return deals.filter((deal) => isPublicDeal(deal) && !isDealExpired(deal, now)).sort(compareDealsForDefault)
}

// Curated homepage picks: strong SulitScore and a sensible (non-suspicious) discount,
// ordered by the same recommended logic so featured leads with safe, practical items
// rather than the biggest discounts or higher-uncertainty electronics.
export function getFeaturedDeals(count = 6, now: Date = new Date()): Deal[] {
  const active = getActiveDeals(now)
  const curated = active
    .filter(d => !isSuspiciousDiscount(d) && d.sulitScore >= 8)
    .sort(compareDealsForDefault)
  const pool = curated.length >= count ? curated : active.filter(d => !isSuspiciousDiscount(d))
  return pool.slice(0, count)
}

export function getRelatedDealsForDeal(current: Deal, count: number, now: Date = new Date()): Deal[] {
  if (!Number.isFinite(count) || count <= 0) return []

  const limit = Math.min(Math.floor(count), 3)
  const currentTags = new Set(current.tags)
  const sharedTagCount = (deal: Deal) => deal.tags.filter((tag) => currentTags.has(tag)).length

  return getActiveDeals(now)
    .filter(
      (deal) =>
        deal.id !== current.id &&
        deal.category === current.category &&
        !isSuspiciousDiscount(deal)
    )
    .sort((a, b) => {
      const aMatchesPlatform = a.platform === current.platform ? 1 : 0
      const bMatchesPlatform = b.platform === current.platform ? 1 : 0
      if (aMatchesPlatform !== bMatchesPlatform) return bMatchesPlatform - aMatchesPlatform

      const aSharedTags = sharedTagCount(a)
      const bSharedTags = sharedTagCount(b)
      if (aSharedTags !== bSharedTags) return bSharedTags - aSharedTags
      if (a.sulitScore !== b.sulitScore) return b.sulitScore - a.sulitScore
      if (a.discount !== b.discount) return b.discount - a.discount
      return a.slug.localeCompare(b.slug)
    })
    .slice(0, limit)
}

// All category labels present in active deals (for filter tabs)
export function getActiveCategories(now: Date = new Date()): string[] {
  const cats = new Set(getActiveDeals(now).map(d => d.category))
  return ["All", ...Array.from(cats).sort()]
}

// Maps category page slugs to deal category values in this data file
const CATEGORY_SLUG_MAP: Record<string, string[]> = {
  "tech-deals":    ["Electronics"],
  "home-finds":    ["Home", "Outdoor"],
  "beauty":        ["Beauty", "Skincare"],
  "fashion":       ["Fashion"],
  "travel":        ["Travel"],
  "digital-tools": ["Digital Tools"],
}

export function getDealsByCategory(categorySlug: string, now: Date = new Date()): Deal[] {
  const active = getActiveDeals(now)
  if (categorySlug === "under-500") {
    return active.filter(d => d.salePrice < 500)
  }
  if (categorySlug === "under-1000") {
    return active.filter(d => d.salePrice < 1000)
  }
  if (categorySlug === "gift-ideas") {
    return active.filter(d => d.sulitScore >= 8)
  }
  const mapped = CATEGORY_SLUG_MAP[categorySlug]
  if (mapped) {
    return active.filter(d => mapped.includes(d.category))
  }
  return active.filter(d => d.category.toLowerCase() === categorySlug.toLowerCase())
}

export function getDealsByPlatform(platform: string, now: Date = new Date()): Deal[] {
  return getActiveDeals(now).filter(d => d.platform === platform)
}
